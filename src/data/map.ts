// Hand-authored with the Héraklios map editor (map-editor.html).
// Coordinates are axial (q, r) for flat-top hexes.
import type { TerrainType } from './terrain';

export interface HexCoord {
  q: number;
  r: number;
}

export function hexKey(q: number, r: number): string {
  return `${q},${r}`;
}

/** Canonical undirected key for the hexside between two adjacent hexes. */
export function riverEdgeKey(a: HexCoord, b: HexCoord): string {
  const lo = a.q < b.q || (a.q === b.q && a.r <= b.r) ? a : b;
  const hi = lo === a ? b : a;
  return `${lo.q},${lo.r}|${hi.q},${hi.r}`;
}

